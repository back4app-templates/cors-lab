// File: scripts/evidence.mjs · turns the rows the test suite recorded (docs/evidence/.rows-local.jsonl)
// into the wire-level evidence file, labeled by target (house convention: <name>-<target>-<date>.md).
// --reset clears the rows before a run (pretest hook).
import { readFileSync, writeFileSync, rmSync, existsSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rowsFile = path.join(root, 'docs', 'evidence', '.rows-local.jsonl');

if (process.argv.includes('--reset')) {
  rmSync(rowsFile, { force: true });
  process.exit(0);
}
if (!existsSync(rowsFile)) {
  console.error('evidence: no rows recorded (run npm test)');
  process.exit(0);
}

const rows = readFileSync(rowsFile, 'utf8').trim().split('\n').map((l) => JSON.parse(l));
const date = new Date().toISOString().slice(0, 10);
const out = path.join(root, 'docs', 'evidence', `wire-matrix-local-${date}.md`);

const esc = (s) => String(s ?? '').replaceAll('|', '\\|').replaceAll('\n', '<br>');

const md = `# Wire-level matrix — LOCAL run, ${date}

Generated by \`npm test\` (scripts/evidence.mjs) from one complete run of the Node test suite against
in-process instances of the lab servers (api/app.mjs, page/app.mjs, cache/proxy.mjs, relay behaviour
reproduced on an ephemeral port). **Local wire evidence only.** Every request in this file is a
**comparison request** sent by a Node HTTP client: it shows what the server answers to an equivalent
request **with no browser involved** — it is never proof about a browser request, and no browser outcome
appears here. The "Server log" column comes from the server's own request log (GET /__state), which is
what distinguishes "the preflight blocked it — no main request executed" from "the request ran and a
browser would merely refuse to expose the response". Browser columns (console text, network-tab status,
what fetch saw) are **to capture** per docs/capture-plan.md.

| Row | Route | Comparison request (Node HTTP client) | Wire answer (status + CORS-relevant headers) | Server log: executed? | Browser outcome |
|---|---|---|---|---|---|
${rows.map((r) => `| ${esc(r.row)} | \`${esc(r.route)}\` | ${esc(r.request)} | ${esc(r.wire)} | ${esc(r.serverLog)} | to capture (browser) |`).join('\n')}

Rows recorded: ${rows.length} · at ${new Date().toISOString()} · node ${process.version}
`;
writeFileSync(out, md);
console.log(`evidence: wrote ${out} (${rows.length} rows)`);
